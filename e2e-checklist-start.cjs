const {chromium}=require('/Users/shenlan/.hermes/cache/scratch/pomodoro-qa/node_modules/playwright');
const assert=require('node:assert/strict');
(async()=>{
  const browser=await chromium.launch();
  try {
    const context=await browser.newContext();
    await context.addInitScript(()=>{window.messages=[];window.webkit={messageHandlers:{native:{postMessage:m=>messages.push(m)}}};});
    const checklist=await context.newPage();
    await checklist.setViewportSize({width:460,height:640});
    const errors=[];checklist.on('pageerror',e=>errors.push(e.message));
    await checklist.goto('file://'+__dirname+'/checklist.html');
    const tasks=[{path:'Test.md',line:2,rawLine:'- [ ] Focus task',text:'Focus task',checked:false,heading:'Tasks'},{path:'Test.md',line:3,rawLine:'- [x] Done task',text:'Done task',checked:true,heading:'Tasks'}];
    await checklist.evaluate(tasks=>{receiveTasks({ok:true,tasks});applyLanguage('zh');},tasks);
    const start=checklist.locator('.taskRow').first().getByRole('button',{name:'开始',exact:true});
    assert.equal(await start.count(),1,'each open task has a Start button');
    assert.equal(await checklist.locator('.taskRow.done button').count(),0);
    await start.click();
    const message=await checklist.evaluate(()=>messages.findLast(m=>m.action==='startTask'));
    assert.deepEqual(message,{action:'startTask',name:'Focus task'});
    assert.equal(await checklist.evaluate(()=>messages.some(m=>m.action==='toggleTask')),false,'Start must not toggle the task');
    assert.equal(await checklist.locator('.taskRow input').first().isChecked(),false);
    const timerPage=await context.newPage();timerPage.on('pageerror',e=>errors.push(e.message));
    await timerPage.setViewportSize({width:247,height:377});
    await timerPage.goto('file://'+__dirname+'/index.html');
    await timerPage.locator('#focusMinutes').fill('42');
    await timerPage.locator('#name').focus();
    assert.equal(await timerPage.evaluate(()=>messages.some(m=>m.action==='loadTimerTasks')),false,'name input no longer opens task selection');
    assert.equal(await timerPage.evaluate(name=>startChecklistTask(name),message.name),true);
    assert.equal(await timerPage.evaluate(()=>messages.filter(m=>m.action==='checklistClose').length),1,'close checklist only after successful task start');
    let state=await timerPage.evaluate(()=>({state:timer.state,name:timer.name,duration:timer.duration,id:timer.id}));
    assert.equal(state.state,'running');assert.equal(state.name,'Focus task');assert.equal(state.duration,2520);
    assert.equal(await timerPage.locator('#active').isVisible(),true);
    assert.equal(await timerPage.evaluate(()=>startChecklistTask('Another task')),false);
    assert.equal(await timerPage.evaluate(()=>timer.id),state.id,'active timer must not be replaced');
    assert.equal(await timerPage.evaluate(()=>messages.filter(m=>m.action==='checklistClose').length),1,'rejected start must keep checklist open');
    await timerPage.locator('#pause').click();
    assert.equal(await timerPage.evaluate(()=>startChecklistTask('Another task')),false);
    assert.equal(await timerPage.evaluate(()=>timer.id),state.id);
    await timerPage.reload();
    assert.equal(await timerPage.evaluate(()=>timer.name),'Focus task');
    assert.equal(await timerPage.evaluate(()=>timer.state),'paused');
    await timerPage.locator('#end').click();
    await timerPage.locator('#note').fill('Retain the previous completion');
    const completedId=await timerPage.evaluate(()=>timer.id);
    assert.equal(await timerPage.evaluate(()=>startChecklistTask('Next checklist task')),true);
    assert.deepEqual(await timerPage.evaluate(()=>({id:timer.pendingNotes[0].id,note:timer.pendingNotes[0].note})),{id:completedId,note:'Retain the previous completion'});
    await timerPage.reload();
    assert.equal(await timerPage.evaluate(()=>timer.pendingNotes[0].note),'Retain the previous completion');
    await timerPage.evaluate(()=>{timer=new Timer();showNotes=false;render();$('focusMinutes').value='0';});
    assert.equal(await timerPage.evaluate(()=>startChecklistTask('Invalid duration')),false);
    assert.equal(await timerPage.evaluate(()=>timer.state),'idle');
    assert.equal(await timerPage.evaluate(()=>messages.some(m=>m.action==='checklistClose')),false,'invalid duration must keep checklist open');
    await timerPage.locator('#focusMinutes').fill('25');
    await timerPage.locator('#name').fill('Custom focus');await timerPage.locator('#name').press('Enter');
    assert.equal(await timerPage.evaluate(()=>timer.name),'Custom focus');
    await timerPage.evaluate(()=>{timer.start('Expired focus',Date.now()-1501000);tickTimer();});
    assert.equal(await timerPage.evaluate(()=>startChecklistTask('Must not skip choice')),false);
    assert.equal(await timerPage.evaluate(()=>timer.awaitingChoice),true);
    await checklist.evaluate(()=>applyLanguage('en'));
    assert.equal(await checklist.locator('.taskStart').first().textContent(),'Start');
    await checklist.locator('.taskText').first().click();
    assert.equal(await checklist.evaluate(()=>messages.findLast(m=>m.action==='toggleTask').checked),true,'task text still toggles checkbox');
    assert.equal(await checklist.locator('.taskStart').first().isDisabled(),true,'cannot start while checkbox write is pending');
    assert.deepEqual(errors,[]);
    console.log('PASS checklist Start bridge, no checkbox mutation, custom duration, removed timer picker, running/paused guards and reload');
  } finally {await browser.close();}
})().catch(e=>{console.error(e);process.exit(1);});
